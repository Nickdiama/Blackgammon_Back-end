DROP TABLE IF EXISTS `board`;
CREATE TABLE `board` (
  `x` int(1) NOT NULL,
  `y` int(1) NOT NULL,
  `piece_color` enum('W','B') DEFAULT NULL,
  PRIMARY KEY (`y`,`x`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

